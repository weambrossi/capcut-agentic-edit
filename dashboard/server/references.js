// Inspiration-video library: metadata in references/library.json (committed), video files in
// references/videos/ (gitignored), and a generated references.md in each style's skill folder
// so Claude finds a style's references through the normal skill-loading path.
import fs from 'node:fs';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { titleFrom } from './skills.js';

const run = promisify(execFile);

export const VIDEO_TYPES = {
  '.mp4': 'video/mp4',
  '.m4v': 'video/mp4',
  '.mov': 'video/quicktime',
  '.webm': 'video/webm',
};
export const MAX_BYTES = 4 * 1024 ** 3;

export function paths(root) {
  const dir = path.join(root, 'references');
  return { dir, videos: path.join(dir, 'videos'), thumbs: path.join(dir, 'thumbs'), library: path.join(dir, 'library.json') };
}

export const thumbPath = (root, id) => path.join(paths(root).thumbs, `${id}.jpg`);

/** One JPEG frame for the grid (gitignored like the videos). Skipped if ffmpeg isn't installed. */
export async function makeThumb(root, id, file, duration) {
  fs.mkdirSync(paths(root).thumbs, { recursive: true });
  const at = duration ? Math.min(1, duration / 2) : 0;
  try {
    await run('ffmpeg', ['-v', 'error', '-y', '-ss', String(at), '-i', file, '-frames:v', '1',
      '-vf', 'scale=640:-2', thumbPath(root, id)]);
    return true;
  } catch {
    return false;
  }
}

export function readLibrary(root) {
  try {
    return JSON.parse(fs.readFileSync(paths(root).library, 'utf8')).videos || [];
  } catch (e) {
    if (e.code === 'ENOENT') return [];
    throw e;
  }
}

export function writeLibrary(root, videos) {
  const { dir, library } = paths(root);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = library + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify({ videos }, null, 2) + '\n');
  fs.renameSync(tmp, library);
}

/** Library entries plus whether the file is on this machine (it's gitignored, so a clone has none). */
export function listReferences(root) {
  return readLibrary(root).map((v) => withLocalState(root, v));
}

export function withLocalState(root, v) {
  return { ...v, available: fs.existsSync(path.join(root, v.file)), thumb: fs.existsSync(thumbPath(root, v.id)) };
}

/** First bytes of the upload must look like the container its extension claims. */
export function sniffVideo(head, ext) {
  if (ext === '.webm') return head.length >= 4 && head.readUInt32BE(0) === 0x1a45dfa3;
  return head.length >= 8 && head.toString('latin1', 4, 8) === 'ftyp';
}

/** Width, height and duration via ffprobe when it's installed; empty otherwise. */
export async function probe(file) {
  try {
    const { stdout } = await run('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries',
      'stream=width,height:format=duration', '-of', 'json', file]);
    const j = JSON.parse(stdout);
    const s = (j.streams || [])[0] || {};
    const duration = Number(j.format?.duration);
    return {
      ...(s.width && { width: s.width, height: s.height }),
      ...(Number.isFinite(duration) && { duration: Math.round(duration * 10) / 10 }),
    };
  } catch {
    return {};
  }
}

const mb = (bytes) => `${(bytes / 1024 ** 2).toFixed(1)} MB`;
const clock = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`;

export function renderReferencesMd(style, videos, styleTitles) {
  const mine = videos.filter((v) => v.styles.includes(style.id));
  const lines = [
    `# Reference videos: ${style.title}`,
    '',
    '<!-- Generated by the dashboard from references/library.json. Edit references in the dashboard; changes here are overwritten. -->',
    '',
    'Videos the user saved as inspiration for this style, with what they like about each. Paths are',
    'relative to the repo root. The files are local only (gitignored): if one is missing on this',
    'machine, say so instead of guessing what it shows.',
    '',
    'A path alone does not let you see a video. To study one, extract frames and look at them, e.g.',
    '`ffmpeg -i <file> -vf fps=1,scale=480:-1 out/ref_frames/%03d.jpg`, and transcribe the audio with',
    '`whisper-cli -m models/ggml-base.en.bin -f <audio.wav>` when speech or music timing matters.',
    '',
  ];
  if (!mine.length) {
    lines.push('No reference videos yet.', '');
    return lines.join('\n');
  }
  for (const v of mine) {
    const info = [v.width && `${v.width}×${v.height}`, v.duration && clock(v.duration), mb(v.size)].filter(Boolean);
    const others = v.styles.filter((s) => s !== style.id).map((s) => styleTitles[s] || titleFrom(s));
    lines.push(`## ${v.name}`, '', `- File: \`${v.file}\` (${info.join(', ')})`);
    if (others.length) lines.push(`- Also a reference for: ${others.join(', ')}`);
    lines.push(`- Added: ${v.addedAt.slice(0, 10)}`);
    if (v.notes) lines.push('', v.notes.trim());
    lines.push('');
  }
  return lines.join('\n');
}

/** Rewrite references.md for every style so it always matches the library. */
export function syncReferenceDocs(root, styles) {
  const videos = readLibrary(root);
  const titles = Object.fromEntries(styles.map((s) => [s.id, s.title]));
  for (const style of styles) {
    const file = path.join(root, '.claude', 'skills', style.id, 'references.md');
    const text = renderReferencesMd(style, videos, titles);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current !== text) fs.writeFileSync(file, text);
  }
}
